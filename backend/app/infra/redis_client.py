"""Async Redis client wrapper for JWT blacklists and OTP rate limiting."""

from typing import Protocol, cast

from redis.asyncio import Redis


class RedisProtocol(Protocol):
    """Minimal async Redis protocol for dependency injection and testing."""

    async def ping(self) -> bool: ...
    async def exists(self, *names: str) -> int: ...
    async def get(self, name: str) -> str | None: ...
    async def set(self, name: str, value: str, *, ex: int | None = None) -> bool | None: ...
    async def incr(self, name: str) -> int: ...
    async def expire(self, name: str, time: int) -> bool: ...
    async def delete(self, *names: str) -> int: ...
    async def aclose(self) -> None: ...


def create_redis_client(redis_url: str) -> RedisProtocol:
    """Creates an async Redis client decoding responses as UTF-8 strings."""
    return cast(RedisProtocol, Redis.from_url(redis_url, decode_responses=True))
